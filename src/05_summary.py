"""Step 5 - Assemble outputs/analysis_summary.md from the verified outputs of steps 1-4.

No number in the summary is typed by hand: every value is read from the JSON/CSV results written by
the earlier scripts, so re-running the pipeline regenerates a consistent document.
"""
from importlib.metadata import version

import pandas as pd

from common import OUT_DIR, STAT_DIR, TAB_DIR, fmt_p, load_json


def section(md_path, start, end=None):
    text = md_path.read_text(encoding="utf-8")
    i = text.index(start) + len(start)
    j = text.index(end, i) if end else len(text)
    return text[i:j].strip()


def main() -> None:
    m1 = load_json(STAT_DIR / "01_inspection_metrics.json")
    m2 = load_json(STAT_DIR / "02_preprocessing_metrics.json")
    R = load_json(STAT_DIR / "03_eda_results.json")
    C = load_json(STAT_DIR / "04_cda_results.json")
    interp = R["interpretations"]
    interp["fig07_cda_lighting_severity.png"] = (
        f"Panel (a) shows adjusted residuals: Daylight has fewer Fatal/Serious and more Slight collisions than independence would predict, while 'Darkness - no lighting' has far more Fatal "
        f"(+{C['top_adjusted_residual_cells'][0]['adj_resid']:.1f}) and Serious collisions and far fewer Slight ones. Panels (b)-(c) give the observed Fatal-or-Serious and Fatal shares with 95% Wilson CIs. "
        f"Only 'no lighting' differs markedly from the overall share on both measures; 'lights lit' is slightly higher than daylight, 'lights unlit' is higher but imprecise (n=720), and 'lighting unknown' is lower. "
        f"{C['interpretation']['practical']}")

    desc = pd.read_csv(TAB_DIR / "03_descriptive_numeric.csv")
    freq = pd.read_csv(TAB_DIR / "03_frequency_tables.csv")
    ft = lambda v: freq[freq.variable == v][["category", "n", "pct_of_all", "pct_of_valid"]].rename(columns={"pct_of_all": "% of all", "pct_of_valid": "% of valid"}).to_markdown(index=False, missingval="-")  # noqa: E731
    sev_light = pd.read_csv(TAB_DIR / "03_severity_by_lighting.csv")[["category", "n", "fatal", "serious", "slight", "fatal_pct", "ksi_pct", "ksi_ci_low", "ksi_ci_high"]].round(2)
    obs = pd.read_csv(TAB_DIR / "04_observed_frequencies.csv")
    exp = pd.read_csv(TAB_DIR / "04_expected_frequencies.csv")
    prop = pd.read_csv(TAB_DIR / "04_severity_proportions_wilson_ci.csv")
    strata = pd.read_csv(TAB_DIR / "04_robustness_stratified_tests.csv")
    figs = sorted(p.name for p in (OUT_DIR / "figures").glob("fig*.png"))

    d = R["desc"]
    cas, veh = d["number_of_casualties"], d["number_of_vehicles"]
    mm = R["monthly"]
    L = []
    a = L.append

    a("# Analysis summary - UK road collisions 2025 (STATS19 collision file)")
    a("")
    a("> Auto-generated by `src/05_summary.py` from the verified outputs of steps 1-4. All figures below come from the executed analysis; nothing was typed by hand. "
      "This is a fact base for the 4-5 page report, not the report itself.")
    a("")

    # 1 ------------------------------------------------------------------ dataset
    a("## 1. Dataset source and description")
    a("")
    a(f"- **Collision file:** `{m1['csv_file']}` ({m1['csv_size_bytes'] / 1e6:.1f} MB, {m1['csv_encoding']}). One row = one police-reported road collision involving personal injury (the STATS19 *collision* table); "
      f"`collision_year` = {m1['collision_year_values']}, dates {m2['date_min']} to {m2['date_max']}.")
    a(f"- **Data guide:** `{m1['guide_file']}` (Department for Transport data guide; sheets {', '.join(f'`{k}`' for k in m1['guide_sheets'])}). Used only to interpret coded values. "
      "The code-list sheet is titled `2024_code_list` and is applied to the 2025 file; every code present in the 2025 data exists in it.")
    a("- **Provenance caveat:** the project folder does not record the download URL or date. The file is the Department for Transport road-safety (STATS19) collision data for 2025; add the exact landing page and access date to the report's reference list.")
    a("- **Coverage:** police-force codes present are those of Great Britain (England, Wales and Police Scotland); no Northern Ireland force appears in the guide or the data, so 'UK' in the project title is really Great Britain.")
    a("- **Content:** collision identifiers, location (OSGR and lat/long), police force, severity (Fatal/Serious/Slight), number of vehicles and casualties, date and time, road class/number/type, speed limit, junction and pedestrian-crossing details, "
      "light, weather and road-surface conditions, special conditions and hazards, urban/rural, police attendance, trunk-road flag, LSOA and DfT severity adjustment fields.")
    a("- **Not in the data:** traffic volumes/exposure, vehicle or casualty details (separate STATS19 tables, deliberately not used), and unreported collisions.")
    a("")

    # 2 ------------------------------------------------------------------ dimensions
    a("## 2. Original and final dataset dimensions")
    a("")
    a(f"| | Original | Processed |\n|:--|--:|--:|\n| Rows | {m2['raw_rows']:,} | {m2['processed_rows']:,} |\n| Columns | {m2['raw_cols']} | {m2['processed_cols']} |")
    a("")
    a(f"No rows were removed ({m2['rows_removed']}). One column was dropped (`{'`, `'.join(m2['dropped_columns'])}`, empty in 2025) and {m2['processed_cols'] - (m2['raw_cols'] - len(m2['dropped_columns']))} added "
      f"(labels, cleaned fields, derived time variables, flags). Raw file SHA-256 is verified unchanged. Processed file: `{m2['processed_file']}` ({m2['processed_size_mb']} MB, not tracked by Git).")
    a("")

    # 3 ------------------------------------------------------------------ preprocessing
    a("## 3. Preprocessing operations and actual results")
    a("")
    a(section(OUT_DIR / "preprocessing_summary.md", "## Operations and results", "## Missing-value handling table"))
    a("")
    a("Full tables: `outputs/preprocessing_summary.md`, `outputs/tables/02_*.csv`.")
    a("")

    # 4 ------------------------------------------------------------------ EDA
    a("## 4. Descriptive statistics and key EDA findings")
    a("")
    a("### 4.1 Numeric variables")
    a("")
    a(desc.to_markdown(index=False))
    a("")
    a(f"Collisions involve a median of {veh['median']:.0f} vehicles (mean {veh['mean']:.2f}, SD {veh['std']:.2f}, max {veh['max']}) and a median of {cas['median']:.0f} casualty "
      f"(mean {cas['mean']:.2f}, SD {cas['std']:.2f}, max {cas['max']}; skewness {cas['skewness']:.1f} - dominated by a few mass-casualty events, so the median is the better summary). "
      f"The most common speed limit (mode) is {d['speed_limit']['mode']:.0f} mph. Mean casualties per collision: Fatal {R['cas_by_sev']['Fatal']:.2f}, Serious {R['cas_by_sev']['Serious']:.2f}, Slight {R['cas_by_sev']['Slight']:.2f}.")
    a("")
    a("### 4.2 Frequency distributions (selected; full set in `outputs/tables/03_frequency_tables.csv`)")
    a("")
    for title, v in [("Collision severity", "severity"), ("Light conditions", "light"), ("Weather", "weather"), ("Road type", "road_type_label"),
                     ("Urban / rural", "area_type"), ("Speed limit (mph)", "speed_limit_mph"), ("Police attendance", "did_police_officer_attend_scene_of_accident_label"),
                     ("Severity reporting basis", "severity_reporting_basis")]:
        a(f"**{title}**")
        a("")
        a(ft(v))
        a("")
    a("### 4.3 Severity by lighting (descriptive)")
    a("")
    a(sev_light.to_markdown(index=False))
    a("")
    a("### 4.4 Key EDA findings")
    a("")
    a(f"1. **Severity is imbalanced:** {R['sev_pct']['Slight']:.1f}% Slight, {R['sev_pct']['Serious']:.1f}% Serious, {R['sev_pct']['Fatal']:.1f}% Fatal ({R['ksi_pct']:.1f}% Fatal or Serious).")
    a(f"2. **Lighting/weather:** most collisions occur in daylight and fine weather (see Figure 2); darkness accounts for {100 - freq[(freq.variable == 'light') & (freq.category == 'Daylight')]['pct_of_valid'].iloc[0]:.1f}% of valid-lighting collisions.")
    a(f"3. **Seasonality:** monthly counts are fairly flat ({R['month_min'][1]:,} in {R['month_min'][0]} to {R['month_max'][1]:,} in {R['month_max'][0]}), but the share in darkness ranges from {R['month_dark_min'][1]:.1f}% ({R['month_dark_min'][0]}) to {R['month_dark_max'][1]:.1f}% ({R['month_dark_max'][0]}). "
      f"The Fatal/Serious share by month ranges from {R['month_ksi_min'][1]:.1f}% ({R['month_ksi_min'][0]}) to {R['month_ksi_max'][1]:.1f}% ({R['month_ksi_max'][0]}).")
    a(f"4. **Time of day:** weekday commuter peaks at 08:00 and {R['hour_peak_weekday']:02d}:00; weekend afternoon peak; the Fatal/Serious share is highest overnight ({R['hour_ksi_max_val']:.1f}% at {R['hour_ksi_max']:02d}:00) and lowest at {R['hour_ksi_min']:02d}:00 ({R['hour_ksi_min_val']:.1f}%). "
      f"Weekday collision counts: Mon {R['weekday_counts']['Monday']:,}, Tue {R['weekday_counts']['Tuesday']:,}, Wed {R['weekday_counts']['Wednesday']:,}, Thu {R['weekday_counts']['Thursday']:,}, Fri {R['weekday_counts']['Friday']:,} (highest), Sat {R['weekday_counts']['Saturday']:,}, Sun {R['weekday_counts']['Sunday']:,} (lowest).")
    a(f"5. **Lighting vs severity:** Fatal/Serious share is {R['light_ksi']['Daylight']['ksi_pct']:.1f}% in daylight vs {R['light_ksi']['Darkness - no lighting']['ksi_pct']:.1f}% in darkness with no lighting; Fatal share {R['light_ksi']['Daylight']['fatal_pct']:.1f}% vs {R['light_ksi']['Darkness - no lighting']['fatal_pct']:.1f}%.")
    a(f"6. **Road environment:** Fatal/Serious share rises with speed limit from {R['speed_ksi']['20']:.1f}% (20 mph) to {R['speed_ksi']['60']:.1f}% (60 mph; {R['speed_ksi']['70']:.1f}% at 70 mph), is higher on single carriageways ({R['roadtype_ksi']['Single carriageway']['ksi_pct']:.1f}%) than roundabouts ({R['roadtype_ksi']['Roundabout']['ksi_pct']:.1f}%), and higher in rural ({R['area_ksi']['Rural']['ksi_pct']:.1f}%) than urban ({R['area_ksi']['Urban']['ksi_pct']:.1f}%) areas.")
    a(f"7. **Reporting effects matter:** the Fatal/Serious share is {R['attend_ksi']['Yes']['ksi_pct']:.1f}% where police attended vs {R['attend_ksi']['No']['ksi_pct']:.1f}% where they did not; {R['unknown_weather_not_attended_pct']:.0f}% of 'Unknown weather' collisions had no police attendance. "
      f"Collisions under injury-based severity reporting have a Fatal/Serious share of {R['reporting_ksi']['Based on Injury code reporting']['ksi_pct']:.1f}% vs {R['reporting_ksi']['Based on severity reporting']['ksi_pct']:.1f}% under officer-reported severity.")
    a(f"8. **Lighting is confounded with road type:** {R['area_share_by_light']['Darkness - no lighting']:.0f}% of 'no lighting' collisions are rural vs {R['area_share_by_light']['Daylight']:.0f}% of daylight collisions (rural share overall {R['rural_share_overall']:.0f}%).")
    a("")

    # 5 ------------------------------------------------------------------ figures
    a("## 5. Figures and interpretations")
    a("")
    a("All figures are in `outputs/figures/` (300 dpi PNG); the numerical tables behind them are in `outputs/tables/`.")
    a("")
    titles = {
        "fig01_severity_distribution.png": "Figure 1 - Severity distribution (`03_frequency_tables.csv`)",
        "fig02_lighting_weather_distribution.png": "Figure 2 - Lighting and weather distributions (`03_frequency_tables.csv`)",
        "fig03_monthly_pattern.png": "Figure 3 - Monthly collisions and share in darkness (`03_monthly_summary.csv`)",
        "fig04_hourly_pattern.png": "Figure 4 - Hourly pattern and Fatal/Serious share (`03_hourly_summary.csv`)",
        "fig05_severity_by_lighting.png": "Figure 5 - Severity by lighting (`03_severity_by_lighting.csv`)",
        "fig06_ksi_by_road_weather.png": "Figure 6 - Fatal/Serious share by speed limit, road type, weather, area (`03_ksi_by_conditions.csv`)",
        "fig07_cda_lighting_severity.png": "Figure 7 - CDA: adjusted residuals and severity shares with 95% CI (`04_*.csv`)",
    }
    for f in figs:
        a(f"### `{f}`")
        a("")
        a(f"*{titles.get(f, f)}*")
        a("")
        a(interp[f])
        a("")

    # 6 ------------------------------------------------------------------ CDA
    a("## 6. Confirmatory data analysis")
    a("")
    a(f"**Research question:** {C['research_question']}")
    a("")
    a(f"- H0: {C['H0']}")
    a(f"- H1: {C['H1']}")
    a(f"- Significance level: alpha = {C['alpha']}")
    a(f"- Test: {C['test']}; analysed n = {C['n_analysed']:,} ({C['n_excluded_missing_lighting']} collisions with missing lighting excluded - complete-case).")
    a("")
    a("**Why this test:** both variables are categorical, observations are distinct collisions, and the expected-count rule is met "
      f"(minimum expected count {C['min_expected']:.2f}; {C['pct_cells_expected_lt5']:.0f}% of cells < 5; {C['cells_expected_lt1']} cells < 1). "
      "No alternative test was needed. Independence of observations cannot be fully verified (collisions cluster in space/time) and the data are a census of reported collisions, not a random sample - see limitations.")
    a("")
    a("**Observed frequencies**")
    a("")
    a(obs.to_markdown(index=False))
    a("")
    a("**Expected frequencies under H0**")
    a("")
    a(exp.round(1).to_markdown(index=False))
    a("")
    a("**Result**")
    a("")
    a(f"- chi-square({C['dof']}) = **{C['chi2']:,.2f}**, p = **{C['p_value_formatted']}** (log10 p = {C['log10_p']:.1f}); decision at alpha = {C['alpha']}: **{C['decision']}**.")
    a(f"- Effect size: Cramér's V = **{C['cramers_v']:.3f}** (95% bootstrap CI {C['cramers_v_ci95'][0]:.3f}-{C['cramers_v_ci95'][1]:.3f}; bias-corrected {C['cramers_v_bias_corrected']:.3f}) - **{C['effect_size_label']}** "
      f"(Cohen benchmarks for df* = {C['df_star']}: {C['cohen_thresholds_small_medium_large'][0]:.3f} / {C['cohen_thresholds_small_medium_large'][1]:.3f} / {C['cohen_thresholds_small_medium_large'][2]:.3f}).")
    a("")
    a("**Severity proportions with 95% Wilson CIs (and risk ratios vs. daylight, Katz CI)**")
    a("")
    a(prop[["lighting", "n", "Fatal_pct", "Fatal_ci_low", "Fatal_ci_high", "KSI (Fatal+Serious)_pct", "KSI (Fatal+Serious)_ci_low", "KSI (Fatal+Serious)_ci_high", "KSI_RR_vs_daylight", "KSI_RR_ci_low", "KSI_RR_ci_high", "Fatal_RR_vs_daylight"]].round(2).to_markdown(index=False, missingval="-"))
    a("")
    a("**Robustness (stratified tests; all four reported)**")
    a("")
    a(strata[["stratifier", "stratum", "n", "chi2", "p_used_text", "cramers_v", "min_expected", "chi2_assumptions_met"]].round(4).to_markdown(index=False))
    a("")
    a("**Conclusions**")
    a("")
    for k in ("decision", "practical", "pattern", "robustness"):
        a(f"- {C['interpretation'][k]}")
    a("- **Plain-language conclusion:** lighting condition and collision severity are not independent in the 2025 reported-collision data, but the overall association is weak; it is driven almost entirely by collisions in darkness with no street lighting, which are more often Fatal or Serious. This is an association, not evidence that darkness causes more severe collisions.")
    a("")
    a("Full detail: `outputs/statistical_results/04_cda_report.md` and `04_cda_results.json`.")
    a("")

    # 7 ------------------------------------------------------------------ limitations
    a("## 7. Limitations and practical implications")
    a("")
    a("**Limitations**")
    a("")
    a("- **No exposure data:** counts of reported collisions are not rates. A larger number or share of collisions in daylight reflects how much travel happens in daylight, not that daylight is more dangerous.")
    a("- **Association only:** lighting correlates with time of day, season, rurality, speed limit and road class. Only two stratified checks were done; no multivariable adjustment (and no modelling, by design).")
    a("- **Measurement of severity and lighting:** severity is recorded under two systems (injury-based and officer-reported), and lighting/weather are officer judgements. "
      f"{R['attend_ksi']['No']['n'] + [v['n'] for k, v in R['attend_ksi'].items() if k.startswith('No -')][0]:,} collisions ({100 * (R['attend_ksi']['No']['n'] + [v['n'] for k, v in R['attend_ksi'].items() if k.startswith('No -')][0]) / R['n']:.1f}%) had no police attendance, and these have much lower Fatal/Serious shares and more 'unknown' codes.")
    a("- **Under-reporting:** STATS19 contains only police-reported injury collisions; slight-injury collisions are known to be under-reported more than serious/fatal ones, which inflates the Fatal/Serious share.")
    a(f"- **Independence:** collisions are not strictly independent (spatial/temporal clustering); nominal p-values are therefore approximate (here p is far below alpha, so the decision is not sensitive).")
    a(f"- **Large n:** with {C['n_analysed']:,} observations, significance is almost guaranteed; the effect size, not the p-value, should carry the interpretation.")
    a("- **Sparse categories:** Fatal collisions in small lighting categories ('lights unlit', 'lighting unknown') rest on few events (19 and 16), so their proportions are imprecise; the 'no police attendance' stratum fails the chi-square expected-count rule and was assessed by Monte Carlo permutation.")
    a(f"- **Data quality notes:** {m2['daylight_00_03h']} 'Daylight' collisions between 00:00 and 03:59 and {m2['dark_10_14h']} 'Darkness' collisions at midday were retained and flagged; `local_authority_district` is empty in the 2025 file; a few new ONS local-authority codes are missing from the guide's list; the guide's `junction_control` code 0 is never used (coded -1 where not at a junction).")
    a("- **Scope:** Great Britain only, a single year, collision-level (not casualty-level) data.")
    a("")
    a("**Practical implications (descriptive, not causal)**")
    a("")
    a(f"- Collisions on unlit roads in darkness are a small share of all collisions ({100 * C['proportions'][3]['n'] / C['n_analysed']:.1f}%) but have a markedly higher Fatal/Serious share; they are a sensible focus for follow-up work on rural-road lighting, speed management and visibility measures. Whether lighting itself would change outcomes cannot be concluded from this dataset.")
    a("- Because lighting interacts with season and hour, any safety messaging about darkness is most relevant in the October-February months and the evening and early-morning hours, when the share of collisions in darkness is highest.")
    a("- Higher Fatal/Serious shares at 60 mph limits, on single carriageways and in rural areas point to road environment and speed as parallel factors worth analysing jointly with lighting.")
    a("- Future work (outside this project's scope): add exposure data, use ordinal or multivariable models to adjust for road type, speed and time, and analyse casualty-level severity.")
    a("")

    # 8 ------------------------------------------------------------------ references
    a("## 8. References and documentation")
    a("")
    a(f"- Department for Transport. *Road safety data (STATS19)*, collision file for 2025 - `{m1['csv_file']}` (add landing-page URL and access date).")
    a(f"- Department for Transport. *Road safety data guide* (field definitions and code lists, sheets `2024_code_list` and `2011_to_2024_conversion`) - `{m1['guide_file']}`.")
    a("- Pearson, K. (1900). On the criterion that a given system of deviations from the probable in the case of a correlated system of variables is such that it can be reasonably supposed to have arisen from random sampling. *Philosophical Magazine*, 50(302), 157-175.")
    a("- Cramér, H. (1946). *Mathematical Methods of Statistics*. Princeton University Press.")
    a("- Cohen, J. (1988). *Statistical Power Analysis for the Behavioral Sciences* (2nd ed.). Lawrence Erlbaum.")
    a("- Bergsma, W. (2013). A bias-correction for Cramér's V and Tschuprow's T. *Journal of the Korean Statistical Society*, 42(3), 323-328.")
    a("- Wilson, E. B. (1927). Probable inference, the law of succession, and statistical inference. *Journal of the American Statistical Association*, 22(158), 209-212.")
    a("- Katz, D., Baptista, J., Azen, S. P., & Pike, M. C. (1978). Obtaining confidence intervals for the risk ratio in cohort studies. *Biometrics*, 34(3), 469-474.")
    a("- Agresti, A. (2013). *Categorical Data Analysis* (3rd ed.). Wiley.")
    a(f"- Software: Python; pandas {version('pandas')}, NumPy {version('numpy')}, SciPy {version('scipy')}, Matplotlib {version('matplotlib')}, seaborn {version('seaborn')}.")
    a("")
    a("### Output index")
    a("")
    a("| Item | Location |\n|:--|:--|\n| Inspection report | `outputs/inspection_report.md` |\n| Preprocessing summary | `outputs/preprocessing_summary.md` |\n| EDA figure interpretations | `outputs/figure_interpretations.md` |\n"
      "| CDA report / JSON results | `outputs/statistical_results/04_cda_report.md`, `04_cda_results.json` |\n| Summary tables | `outputs/tables/*.csv` |\n| Figures | `outputs/figures/fig01..fig07*.png` |\n| Processed data | `data/processed/collisions_2025_processed.csv` |")
    (OUT_DIR / "analysis_summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"analysis_summary.md written ({len(L)} lines)")


if __name__ == "__main__":
    main()
